public class modelMahasiswa {
    
    String NIM, nama;

    public modelMahasiswa() {
    }

    public modelMahasiswa(String NIM, String nama) {
        this.NIM = NIM;
        this.nama = nama;
    }

    public String getNIM() {
        return NIM;
    }

    public void setNIM(String NIM) {
        this.NIM = NIM;
    }

    public String getNama() {
        return nama;
    }

    public void setNama(String nama) {
        this.nama = nama;
    }
    
    
    
}
