    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        String tanggal = new SimpleDateFormat("yyyy-MM-dd").format(tTanggal.getDate());
        modelPemasukan pemasukan = new modelPemasukan(
                UUID.randomUUID().toString(),
                tanggal,
                tPengguna.getText(),
                Integer.parseInt(tNominal.getText()),
                tKeterangan.getText()
        );

        boolean simpan = pemasukan.tambah();
        if (simpan == true) {
            JOptionPane.showMessageDialog(null, "Data Berhasil Disimpan");
        } else {
            JOptionPane.showMessageDialog(null, "Data Gagal Disimpan");
        }
        reset();
        loadTable();
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void tPemasukanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tPemasukanMouseClicked
        // TODO add your handling code here:
        int baris = tPemasukan.getSelectedRow();

        String id = tPemasukan.getValueAt(baris, 0).toString();
        String tanggal = tPemasukan.getValueAt(baris, 1).toString();
        String pengguna = tPemasukan.getValueAt(baris, 2).toString();
        String nominal = tPemasukan.getValueAt(baris, 3).toString();
        String keterangan = tPemasukan.getValueAt(baris, 4).toString();

        tID.setText(id);
        
        if (tanggal != null && !tanggal.isEmpty()) {
            try {
                tTanggal.setDate(java.sql.Date.valueOf(tanggal));
            } catch (IllegalArgumentException e) {
                // Jika gagal parsing tanggal, kosongkan field tanggal
                tTanggal.setDate(null);
            }
        } else {
            tTanggal.setDate(null);
        }
        
        tPengguna.setText(pengguna);
        tNominal.setText(nominal);
        tKeterangan.setText(keterangan);
    }//GEN-LAST:event_tPemasukanMouseClicked

